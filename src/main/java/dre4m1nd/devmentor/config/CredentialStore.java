package dre4m1nd.devmentor.config;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermission;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.LinkedHashMap;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * 凭据的本地持久化：{@code /login} 输入的 Key 落盘到用户目录，下次启动自动读取。
 *
 * <p>存储位置是 {@code ~/.devmentor/credentials}（不在工作区里，避免随项目提交），
 * 格式是极简的 {@code provider=key} 一行一条。**不加密**——只是放在用户主目录并收紧
 * 文件权限（POSIX 下 0600）。真要更强的保护，应当交给系统钥匙串，这里刻意不引入
 * 平台相关依赖。
 *
 * <p>读取优先级：环境变量 &gt; 本地凭据文件 &gt; 配置文件。这样 CI 里用环境变量注入
 * 就能覆盖本地文件，不会被开发机的 Key 干扰。
 */
public final class CredentialStore {

    private static final Logger log = LoggerFactory.getLogger(CredentialStore.class);

    private final Path file;

    public CredentialStore(Path file) {
        this.file = file;
    }

    /** 默认位置：{@code ~/.devmentor/credentials}。 */
    public static CredentialStore defaultStore() {
        String home = System.getProperty("user.home", ".");
        return new CredentialStore(Path.of(home, ".devmentor", "credentials"));
    }

    public Path file() {
        return file;
    }

    /** 读出全部已保存的 provider → key。文件不存在时返回空表。 */
    public Map<String, String> load() {
        Map<String, String> result = new LinkedHashMap<>();
        if (!Files.isRegularFile(file)) {
            return result;
        }
        try {
            for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
                String trimmed = line.trim();
                if (trimmed.isEmpty() || trimmed.startsWith("#")) {
                    continue;
                }
                int eq = trimmed.indexOf('=');
                if (eq <= 0) {
                    continue;
                }
                String provider = trimmed.substring(0, eq).trim().toLowerCase(Locale.ROOT);
                String key = trimmed.substring(eq + 1).trim();
                if (!provider.isEmpty() && !key.isEmpty()) {
                    result.put(provider, key);
                }
            }
        } catch (IOException e) {
            log.warn("读取凭据文件失败: {}", e.getMessage());
        }
        return result;
    }

    /** 保存一个 provider 的 key（覆盖同名项）。 */
    public void save(String provider, String key) throws IOException {
        Map<String, String> all = load();
        all.put(provider.toLowerCase(Locale.ROOT), key);
        write(all);
    }

    /** 删除一个 provider 的 key。 */
    public void remove(String provider) throws IOException {
        Map<String, String> all = load();
        if (all.remove(provider.toLowerCase(Locale.ROOT)) != null) {
            write(all);
        }
    }

    /** 按 provider 查找已保存的 key；没有则返回 {@code null}。 */
    public String find(String provider) {
        if (provider == null) {
            return null;
        }
        return load().get(provider.toLowerCase(Locale.ROOT));
    }

    private void write(Map<String, String> all) throws IOException {
        Path parent = file.getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }
        StringBuilder sb = new StringBuilder();
        sb.append("# DevMentor credentials - generated by /login\n");
        sb.append("# 一行一个 provider=key，请勿提交到版本库。\n");
        all.forEach((provider, key) -> sb.append(provider).append('=').append(key).append('\n'));
        Files.writeString(file, sb.toString(), StandardCharsets.UTF_8);
        tightenPermissions();
    }

    /**
     * 尽力把文件权限收紧到 0600。
     *
     * <p>Windows 上不支持 POSIX 权限，此处静默跳过——不是错误，只是做不到。
     */
    private void tightenPermissions() {
        try {
            Set<PosixFilePermission> perms = PosixFilePermissions.fromString("rw-------");
            Files.setPosixFilePermissions(file, perms);
        } catch (UnsupportedOperationException | IOException ignored) {
            // Windows 等非 POSIX 文件系统：跳过
        }
    }
}
